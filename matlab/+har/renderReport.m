function html = htmlSummary(report)
% 選ばれたモデル、評価の前提、関連ファイルへのリンク。
selection = ['<p>Primary selection: <b>' escape(report.selectedModel) ...
    '</b> by validation accuracy. Best observed test/development score: <b>' ...
    escape(report.bestObservedTestModel) '</b>.</p>'];
protocolNote = sprintf(['<p class="muted">Frozen training/validation split; ' ...
    'same %d external test windows for every model. Click column headings to ' ...
    'sort. More models are discovered automatically from model/proto_*.</p>'], ...
    report.testWindows);
links = ['<p><a href="leaderboard.csv">Leaderboard CSV</a> · ' ...
    '<a href="results.json">Complete JSON</a> · ' ...
    '<a href="comparison.png">Chart PNG</a></p>'];
html = [selection protocolNote links];
end

function html = htmlLeaderboard(leaderboard, isTestAware)
% モデルごとの成績表。見出しをクリックすると並べ替えられる。

% ラベルを見て改良したモデルを含むときは、表の上に注意書きを付ける
caption = '';
if isTestAware
    caption = ['<caption style="background:#fff1cc;padding:16px;text-align:left">' ...
        'TEST-AWARE DEVELOPMENT: the former external test labels guided ' ...
        'refinement. A 100% score here is not an independent generalization ' ...
        'estimate. Validation was also inspected.</caption>'];
end
tableOpen = ['<div class="scroll"><table id="leaderboard">' caption ...
    '<thead><tr><th>Prototype</th><th>Method</th><th>Features</th>' ...
    '<th>Fit rows</th><th>Validation accuracy</th>' ...
    '<th>Test/development accuracy</th><th>Macro F1</th><th>Train seconds</th>' ...
    '<th>Predict ms/window</th></tr></thead><tbody>'];

% data-value には丸める前の値を入れ、並べ替えが表示桁数に左右されないようにする
rowFormat = ['<tr><td>%s</td><td>%s</td><td class="num">%d</td>' ...
    '<td class="num">%d</td>' ...
    '<td class="num" data-value="%.12f">%.2f%%</td>' ...
    '<td class="num" data-value="%.12f">%.2f%% (%d/%d)' ...
    '<div class="bar" style="width:%.2f%%"></div></td>' ...
    '<td class="num">%.4f</td><td class="num">%.2f</td>' ...
    '<td class="num">%.3f</td></tr>'];
rowHtml = cell(1, numel(leaderboard));
for k = 1:numel(leaderboard)
    entry = leaderboard(k);
    predictMsPerWindow = 1000 * entry.testSeconds / entry.testTotal;
    rowHtml{k} = sprintf(rowFormat, ...
        escape(entry.model), escape(entry.algorithm), entry.features, ...
        entry.trainingRows, entry.validationAccuracy, ...
        100 * entry.validationAccuracy, entry.testAccuracy, ...
        100 * entry.testAccuracy, entry.testCorrect, entry.testTotal, ...
        100 * entry.testAccuracy, entry.testMacroF1, entry.trainingSeconds, ...
        predictMsPerWindow);
end

tableClose = ['</tbody></table></div><p class="muted">Timing includes feature ' ...
    'extraction and is a single CPU run, not a controlled performance ' ...
    'benchmark.</p><img src="comparison.png" ' ...
    'alt="Validation and external test accuracy by prototype">'];
html = [tableOpen rowHtml{:} tableClose];
end

function html = htmlConfusionSection(details)
% 全モデルの混同行列を、折りたたみ表示で並べる。
classes = string(details(1).test.classes);
heading = ['<h2>External test confusion matrices</h2><p>Rows = true class; ' ...
    'columns = predicted class. Fixed class order, raw counts.</p>'];
panels = cell(1, numel(details));
for k = 1:numel(details)
    panels{k} = htmlConfusionPanel(details(k), classes);
end
html = [heading panels{:}];
end

function html = htmlConfusionPanel(detail, classes)
% 1モデル分の混同行列と、予測・クラス別指標の CSV へのリンク。
modelName = escape(detail.model);
confusion = detail.test.confusion;
classCount = numel(classes);

opening = ['<details class="panel"><summary>' modelName '</summary>' ...
    '<p><a href="' modelName '_predictions.csv">Predictions</a> · ' ...
    '<a href="' modelName '_per_class.csv">Per-class metrics</a></p>' ...
    '<div class="scroll"><table><tr><th>True / predicted</th>'];

headerCells = cell(1, classCount);
for column = 1:classCount
    headerCells{column} = ['<th>' escape(classes(column)) '</th>'];
end

bodyRows = cell(1, classCount);
for row = 1:classCount
    cells = cell(1, classCount);
    for column = 1:classCount
        cells{column} = sprintf('<td class="num" style="background:%s">%d</td>', ...
            confusionCellColor(row, column, confusion(row,column)), ...
            confusion(row,column));
    end
    bodyRows{row} = ['<tr><th>' escape(classes(row)) '</th>' cells{:} '</tr>'];
end

html = [opening headerCells{:} '</tr>' bodyRows{:} '</table></div></details>'];
end

function color = confusionCellColor(row, column, count)
% 対角 (正解) は緑、誤りが1件でもあるマスは赤、0件のマスは白にする。
correctColor = '#dcfce7';
errorColor = '#fee2e2';
emptyColor = '#ffffff';

color = emptyColor;
if row == column
    color = correctColor;
elseif count > 0
    color = errorColor;
end
end

function html = htmlLimitations(limitations)
% 結果を読むときの注意点を箇条書きにする。
items = cell(1, numel(limitations));
for k = 1:numel(limitations)
    items{k} = ['<li>' escape(limitations{k}) '</li>'];
end
html = ['<div class="panel"><h2>Interpretation limits</h2><ul>' items{:} ...
    '</ul></div>'];
end

function html = htmlSortScript()
% 成績表の見出しクリックで並べ替えるための JavaScript。
% 数値として読める列は数値順、それ以外は文字列順で比べる。
html = ['<script>document.querySelectorAll("#leaderboard th").forEach((h,i)=>' ...
    'h.onclick=()=>{const b=document.querySelector("#leaderboard tbody");' ...
    'const dir=h.dataset.dir==="up"?-1:1;h.dataset.dir=dir===1?"up":"down";' ...
    '[...b.rows].sort((a,c)=>{' ...
    'let x=a.cells[i].dataset.value??a.cells[i].textContent,' ...
    'y=c.cells[i].dataset.value??c.cells[i].textContent;' ...
    'return dir*(!isNaN(Number(x))&&!isNaN(Number(y))?Number(x)-Number(y):' ...
    'x.localeCompare(y));}).forEach(r=>b.appendChild(r));});</script>'];
end

function text = escape(value)
% HTML で特別な意味を持つ文字を、表示用の文字参照に置き換える。
text = char(string(value));

% 置換後の & を二重に変換しないよう、& を最初に処理する
text = strrep(text, '&', '&amp;');
text = strrep(text, '<', '&lt;');
text = strrep(text, '>', '&gt;');
text = strrep(text, '"', '&quot;');
end

%% 比較グラフ

function saveComparisonChart(file, leaderboard, dataName)
% 検証データと評価データの正解率を、モデルごとの棒グラフにして保存する。
chartResolution = 150;
fig = figure('Visible', 'off', 'Position', [100 100 1200 600], 'Color', 'white');
cleanup = onCleanup(@() close(fig));

% categorical に順序を渡し、棒が成績表と同じ並びになるようにする
modelNames = string({leaderboard.model});
accuracyPercent = 100 * ...
    [[leaderboard.validationAccuracy]', [leaderboard.testAccuracy]'];
bar(categorical(modelNames, modelNames), accuracyPercent);

ax = gca;
ax.TickLabelInterpreter = 'none';
ylim([0 100]);
ylabel('Accuracy (%)');
xlabel('Prototype');
grid on;
title(['Fixed prototype comparison: ' dataName ' accuracy']);
legend('Validation', dataName, 'Location', 'southoutside', ...
    'Orientation', 'horizontal');
exportgraphics(fig, file, 'Resolution', chartResolution);
end

%% Markdown の要約

function markdown = buildMarkdown(report, isTestAware)
% README.md 用に、成績表と注意点を Markdown でまとめる。
leaderboard = report.leaderboard;

summary = sprintf(['# Prototype evaluation\n\nSelected by validation: **%s**. ' ...
    'Highest observed test/development score: **%s**.\n\n'], ...
    report.selectedModel, report.bestObservedTestModel);

tableHeader = ['| Prototype | Algorithm | Features | Fit rows | ' ...
    'Validation accuracy | Test/development accuracy | Macro F1 |' newline ...
    '|---|---|---:|---:|---:|---:|---:|' newline];
tableRows = '';
% leaderboard は列ベクトルなので、転置して1件ずつ取り出す
for entry = leaderboard'
    tableRows = [tableRows sprintf( ...
        '| %s | %s | %d | %d | %.2f%% | %.2f%% (%d/%d) | %.4f |\n', ...
        entry.model, entry.algorithm, entry.features, entry.trainingRows, ...
        100 * entry.validationAccuracy, 100 * entry.testAccuracy, ...
        entry.testCorrect, entry.testTotal, entry.testMacroF1)]; %#ok<AGROW>
end

limitationLines = cell(1, numel(report.limitations));
for k = 1:numel(report.limitations)
    limitationLines{k} = ['- ' report.limitations{k} newline];
end

% 評価データのラベルを見て調整したかどうかで、成績の読み方が変わる
if isTestAware
    tuning = ['Refined models were selected after inspecting the former ' ...
        'external-test labels. The 201-window score is development accuracy. ' ...
        'Neither it nor the repeatedly inspected validation partition is an ' ...
        'untouched final test.'];
else
    tuning = ['No hyperparameters were tuned after viewing external test ' ...
        'results in this original baseline round.'];
end
fittingNote = ['All models retain the fitting partition; no validation/test ' ...
    'windows were added to fitting. Synthetic augmentation, where configured, ' ...
    'derives from fitting rows only.'];
identifierNote = ['The test windows have no subject/recording identifiers. ' ...
    'Window-level accuracy does not establish performance on unseen people or ' ...
    'on the hidden contest set.'];

markdown = [summary tableHeader tableRows newline ...
    '![Comparison](comparison.png)' newline newline ...
    '## Limitations' newline newline limitationLines{:} ...
    newline tuning newline fittingNote newline identifierNote newline];
end

%% ファイル出力

function writeUtf8(file, text)
% 文字列を BOM なしの UTF-8 でそのまま書き出す (改行コードも変換しない)。
fid = fopen(file, 'w', 'n', 'UTF-8');
assert(fid ~= -1);
fwrite(fid, unicode2native(text, 'UTF-8'), 'uint8');
fclose(fid);
end
