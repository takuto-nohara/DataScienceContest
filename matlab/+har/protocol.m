function protocol = protocol(root, data)
% 学習用データを「学習に使う行」と「検証に使う行」に分ける取り決めを返す。
%
% 分け方は evaluation/protocol.json に保存してあり、すべてのモデルが同じ
% 分け方を使う。ファイルがなければ、行動ごとの割合を保って75%と25%に分け、
% 保存する。

protocolFile = fullfile(root, 'evaluation', 'protocol.json');

if isfile(protocolFile)
    protocol = jsondecode(fileread(protocolFile));
    assert(isequal(protocol.fingerprint, data.fingerprint), ...
        'Dataset changed: create a new protocol version.');
else
    seed = 224224;
    validationFraction = 0.25;
    rng(seed, 'twister');
    partition = cvpartition(categorical(data.trainLabels), ...
        'Holdout', validationFraction);

    protocol = struct( ...
        'version', 'protocol_v1', ...
        'seed', seed, ...
        'fingerprint', data.fingerprint, ...
        'fitRows', find(training(partition)), ...
        'validationRows', find(test(partition)), ...
        'classes', data.classes, ...
        'selectionMetric', 'validation_accuracy', ...
        'testRole', 'Fixed external comparison only; do not tune on these labels', ...
        'limitation', ['Random stratified windows; no subject IDs or recording ' ...
            'IDs provided. Overlap leakage cannot be excluded. ' ...
            'Not an unseen-subject estimate.']);
    har.writeJson(protocolFile, protocol);
end

% 2つの組が重ならず、合わせると全行になることを確かめる。
fitRows = protocol.fitRows(:);
validationRows = protocol.validationRows(:);
allRows = (1:numel(data.trainLabels))';
assert(isempty(intersect(fitRows, validationRows)) ...
    && isequal(sort([fitRows; validationRows]), allRows), 'Invalid partition.');
end
