function renderReport(root, out, report) %#ok<INUSD>
% 評価結果 (report) から、比較レポート一式を out フォルダに書き出す。
% 出力は report.html、comparison.png、README.md の3つ。
% root は使わないが、呼び出し側との取り決めを変えないために残している。

% 開発用にラベルを見たモデルが混じるなら「外部テスト」とは呼ばない
isTestAware = isfield(report, 'containsTestAwareModels') ...
    && report.containsTestAwareModels;
dataName = 'External test';
if isTestAware
    dataName = 'Development (test-aware)';
end

writeUtf8(fullfile(out, 'report.html'), buildHtml(report, isTestAware));
saveComparisonChart(fullfile(out, 'comparison.png'), report.leaderboard, dataName);
writeUtf8(fullfile(out, 'README.md'), buildMarkdown(report, isTestAware));
fprintf('Report: %s\n', fullfile(out, 'report.html'));
end

%% HTML レポート

function html = buildHtml(report, isTestAware)
% report.html 全体を、上から順に部品をつないで作る。
html = [htmlHead() ...
    htmlSummary(report) ...
    htmlLeaderboard(report.leaderboard, isTestAware) ...
    htmlConfusionSection(report.details) ...
    htmlLimitations(report.limitations) ...
    htmlSortScript() ...
    '</html>'];
end

